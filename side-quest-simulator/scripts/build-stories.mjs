import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { validatePacks } from './story-format.mjs';

const root = new URL('../', import.meta.url);
try {
  const files = (await readdir(new URL('stories/', root))).filter((f) => f.endsWith('.json')).sort();
  const packs = await Promise.all(files.map(async (file) => [file, JSON.parse(await readFile(new URL(`stories/${file}`, root), 'utf8'))]));
  const { stories, rivals, extraObjectives } = validatePacks(packs);
  const output = '// Generated by npm run stories:build. Edit stories/*.json instead.\n' +
    "import type { Objective, QuestStory, StoryScene } from '../types';\n\n" +
    `export const STORIES: QuestStory[] = ${JSON.stringify(stories, null, 2)};\n\n` +
    `export const RIVAL_SCENES: StoryScene[] = ${JSON.stringify(rivals, null, 2)};\n\n` +
    `export const EXTRA_OBJECTIVES: Objective[] = ${JSON.stringify(extraObjectives, null, 2)};\n`;
  const target = new URL('src/game/content/stories.generated.ts', root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== output) throw new Error('Generated stories are stale. Run npm run stories:build.');
  } else await writeFile(target, output);
  console.log(`${stories.length} quest stories, ${stories.reduce((n, s) => n + s.scenes.length, 0)} scenes, ${rivals.length} rival encounters. ${process.argv.includes('--check') ? 'Up to date.' : fileURLToPath(target)}`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
